"""Fake providers for tests.

They return scripted results, count how often they are called, and charge the
RunBudget exactly like the real providers do, so limits behave realistically.
They never touch the network.
"""

from typing import NamedTuple

from app.services.question_generation_provider import (
    GeneratedCandidate,
    GenerationResult,
)
from app.services.question_search_provider import CandidateQuestion


def _split(item):
    """An item is a question text or a (text, difficulty, description) tuple."""
    if isinstance(item, str):
        return item, None, None
    text, difficulty, description = item
    return text, difficulty, description


class FakeSearch:
    """Each call returns the next batch of question texts, or nothing."""

    def __init__(self, batches=None, *, error=None, errors_by_category=None):
        self.batches = [list(batch) for batch in (batches or [])]
        self.error = error
        self.errors_by_category = dict(errors_by_category or {})
        self.calls: list[tuple[str, str]] = []  # (category, query)
        self.closed = False

    def search_questions(self, category, query, budget):
        budget.consume_search(category)  # charged before the "request"
        self.calls.append((category, query))

        error = self.errors_by_category.get(category, self.error)
        if error is not None:
            raise error

        texts = self.batches.pop(0) if self.batches else []
        return [
            CandidateQuestion(
                text=_split(item)[0],
                source_url=f"https://site.example/{index}",
                source_title="Page",
                source_domain="site.example",
                search_query=query,
                provider="tavily",
                attribution="Found on site.example through web search.",
            )
            for index, item in enumerate(texts)
        ]

    def close(self):
        self.closed = True


class GenerationCall(NamedTuple):
    category: str
    count: int
    avoid: list[str]


class FakeGenerator:
    """Each call returns the next batch, or nothing once the batches run out."""

    def __init__(
        self,
        batches=None,
        *,
        error=None,
        errors_by_category=None,
        tokens=500,
        difficulty="Intermediate",
        model="fake-model",
        rejected_per_call=0,
    ):
        self.batches = [list(batch) for batch in (batches or [])]
        self.error = error
        self.errors_by_category = dict(errors_by_category or {})
        self.tokens = tokens
        self.difficulty = difficulty
        self.model = model
        self.rejected_per_call = rejected_per_call
        self.calls: list[GenerationCall] = []

    def generate_questions(self, category, count, budget, avoid=()):
        budget.consume_ai_call(category)  # charged before the "request"
        self.calls.append(GenerationCall(category, count, list(avoid)))

        error = self.errors_by_category.get(category, self.error)
        if error is not None:
            raise error

        budget.add_tokens(category, self.tokens)
        texts = self.batches.pop(0) if self.batches else []

        candidates = []
        for item in texts:
            text, difficulty, description = _split(item)
            candidates.append(
                GeneratedCandidate(
                    text=text,
                    difficulty=difficulty or self.difficulty,
                    description=description,
                    category=category,
                    provider="gemini",
                    model_name=self.model,
                    attribution=f"AI-generated by {self.model}. Not sourced from a website.",
                )
            )

        return GenerationResult(
            candidates=candidates,
            rejected=self.rejected_per_call,
            tokens_used=self.tokens,
            model=self.model,
        )