def test_a_deactivated_question_keeps_working_for_existing_practice(env):
    created = env.client.post(
        "/api/practice/sessions", headers=env.member, json={"question_id": env.ids.ai}
    )
    assert created.status_code == 201
    session_id = created.json()["id"]

    call(env, "patch", f"/questions/{env.ids.ai}", env.admin, {"is_active": False})

    # Old sessions, reports and history still open the question by id...
    question = env.client.get(f"/api/questions/{env.ids.ai}")
    assert question.status_code == 200
    assert question.json()["is_active"] is False
    session = env.client.get(f"/api/practice/sessions/{session_id}", headers=env.member)
    assert session.status_code == 200

    # ...but nobody can start new practice with it, and it is not listed.
    retry = env.client.post(
        "/api/practice/sessions", headers=env.member, json={"question_id": env.ids.ai}
    )
    assert retry.status_code == 404
    listed = {item["id"] for item in env.client.get("/api/questions/").json()}
    assert env.ids.ai not in listed
    assert {env.ids.manual, env.ids.web} <= listed


