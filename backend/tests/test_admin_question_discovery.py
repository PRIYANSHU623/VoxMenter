def call(env, method, path, headers=None, body=None, **params):
    kwargs = {}
    if headers is not None:
        kwargs["headers"] = headers
    if body is not None:
        kwargs["json"] = body
    if params:
        kwargs["params"] = params
    return env.client.request(method.upper(), BASE + path, **kwargs)


