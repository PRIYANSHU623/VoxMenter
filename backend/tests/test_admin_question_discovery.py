class FakeRedisClient:
    def __init__(self, result=0, error=None):
        self.result = result
        self.error = error
        self.keys = []
        self.disconnects = 0
        self.connection_pool = SimpleNamespace(disconnect=self._disconnect)

    def _disconnect(self):
        self.disconnects += 1

    def exists(self, key):
        self.keys.append(key)
        if self.error is not None:
            raise self.error
        return self.result


def patch_redis(monkeypatch, client):
    created = []

    def from_url(url, **options):
        created.append((url, options))
        return client

    monkeypatch.setattr(admin_api, "Redis", SimpleNamespace(from_url=from_url))
    return created


@pytest.mark.parametrize(("result", "expected"), [(1, True), (0, False)])
def test_the_lock_check_reads_the_discovery_lock(monkeypatch, result, expected):
    client = FakeRedisClient(result=result)
    created = patch_redis(monkeypatch, client)

    assert admin_api._lock_held() is expected

    assert client.keys == [LOCK_NAME]
    assert client.disconnects == 1
    url, options = created[0]
    assert url == config.LOCK_REDIS_URL
    assert options["socket_connect_timeout"] == 2  # a slow Redis cannot hang the page


@pytest.mark.parametrize("error", [RedisConnectionError("down"), OSError("unreachable")])
def test_the_lock_check_gives_up_quietly_when_redis_is_unreachable(monkeypatch, error):
    client = FakeRedisClient(error=error)
    patch_redis(monkeypatch, client)

    assert admin_api._lock_held() is None
    assert client.disconnects == 1


